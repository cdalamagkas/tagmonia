Deno.test("links: playlists and videos from every YouTube host; a watch link in a playlist means the playlist", () => {
  const p = (s: string) => parseYouTubeUrl(new URL(s));
  assertEquals(p("https://music.youtube.com/playlist?list=OLAK5uy_kAbCdEfGhIjKlMnOp"), {
    kind: "playlist",
    id: "OLAK5uy_kAbCdEfGhIjKlMnOp",
  });
  assertEquals(p("https://www.youtube.com/watch?v=jNQXAC9IVRw&list=PLabcdefghij"), {
    kind: "playlist",
    id: "PLabcdefghij",
  });
  assertEquals(p("https://youtu.be/jNQXAC9IVRw"), { kind: "video", id: "jNQXAC9IVRw" });
  assertEquals(p("https://m.youtube.com/watch?v=jNQXAC9IVRw"), { kind: "video", id: "jNQXAC9IVRw" });
  assert("error" in p("http://www.youtube.com/watch?v=jNQXAC9IVRw"), "https only");
  assert("error" in p("https://www.youtube.com/watch?v=short"));
  assert("error" in p("https://music.youtube.com/browse/MPREb_abc"), "album pages are not in the Data API");
  assert("error" in p("https://youtube.com.example/watch?v=jNQXAC9IVRw"));
});

Deno.test("durations and the release facts of an auto-generated description", () => {
  assertEquals([parseDuration("PT4M46S"), parseDuration("PT1H2M"), parseDuration("P0D"), parseDuration("x")], [
    286_000,
    3_720_000,
    null,
    null,
  ]);
  assertEquals(parseDescription(description("Morning")), {
    providedBy: "DistroKid",
    track: { title: "Morning", artists: ["Niklas Blumenthaler"] },
    album: "Ambient Piano Vol.1",
    label: "LKult",
    date: "2021-07-23",
  });
  assertEquals(
    parseDescription("Provided to YouTube by Sony\n\nSong · Artist\n\nAlbum\n\n℗ 2003 RCA Records, a division of Sony"),
    {
      providedBy: "Sony",
      track: { title: "Song", artists: ["Artist"] },
      album: "Album",
      label: "RCA Records",
      date: null,
    },
  );
  assertEquals(parseDescription("My holiday video\n℗ nothing"), {
    providedBy: null,
    track: null,
    album: null,
    label: null,
    date: null,
  }, "only auto-generated uploads count");
});

async function setup(routes: Record<string, unknown>) {
  const db = await openMigratedDb(":memory:");
  const seen: { url: URL; key: string | null }[] = [];
  const fetch: typeof globalThis.fetch = (input, init) => {
    const url = new URL(String(input));
    seen.push({ url, key: new Headers(init?.headers).get("x-goog-api-key") });
    const path = `${url.pathname.replace("/youtube/v3/", "")}${url.searchParams.get("pageToken") ?? ""}`;
    const body = routes[path];
    return Promise.resolve(
      body instanceof Response ? body : new Response(JSON.stringify(body ?? { items: [] }), { status: 200 }),
    );
  };
  const clock = new FakeClock();
  const client = new YouTubeClient({
    apiKey: KEY,
    cache: new SnapshotCache(db, await Deno.makeTempDir({ prefix: "tagmonia-youtube-" })),
    http: { userAgent: USER_AGENT, fetch, clock, limiter: new RateLimiter({ requests: 5, perMs: 1000 }, clock) },
  });
  return { client, seen, db };
}

const video = (id: string, title: string, duration: string, desc = description(title)) => ({
  id,
  snippet: { title, description: desc, channelTitle: "Niklas Blumenthaler - Topic" },
  contentDetails: { duration },
});

Deno.test("a playlist: every page of videos, their lengths, and the facts most uploads agree on", async () => {
  const ids = ["aaaaaaaaaaa", "bbbbbbbbbbb", "ccccccccccc"];
  const { client, seen, db } = await setup({
    playlists: { items: [{ snippet: { title: "Album - Ambient Piano Vol.1", channelTitle: "Niklas - Topic" } }] },
    playlistItems: {
      nextPageToken: "P2",
      items: ids.slice(0, 2).map((videoId) => ({ contentDetails: { videoId } })),
    },
    playlistItemsP2: { items: [{ contentDetails: { videoId: ids[2] } }] },
    videos: {
      // The third is deleted: it is not returned, but keeps its place.
      items: [
        video(ids[0], "Morning", "PT3M1S"),
        video(ids[1], "Noon", "PT2M", description("Noon", "2021-07-20")),
      ],
    },
  });
  try {
    const e = await client.evidence({ kind: "playlist", id: "OLAK5uy_test0001" });
    assertEquals(e.title, "Album - Ambient Piano Vol.1");
    assertEquals(e.tracks.map((t) => [t.title, t.durationMs, t.name, t.artists]), [
      ["Morning", 181_000, "Morning", ["Niklas Blumenthaler"]],
      ["Noon", 120_000, "Noon", ["Niklas Blumenthaler"]],
      ["(unavailable video)", null, null, []],
    ]);
    assertEquals([e.label, e.album, e.providedBy], ["LKult", "Ambient Piano Vol.1", "DistroKid"]);
    assertEquals(e.date, "2021-07-23", "a tie goes to the first track's");
    assertEquals(e.url, "https://www.youtube.com/playlist?list=OLAK5uy_test0001");
    // The key only ever travels in a header: not in a URL, so not in the cache or a log line.
    assert(seen.every((s) => s.key === KEY && !s.url.href.includes(KEY)));
    const keys = db.prepare("SELECT request_key FROM snapshot").all() as { request_key: string }[];
    assert(keys.length > 0 && keys.every((k) => !k.request_key.includes(KEY)));

    const n = seen.length;
    await client.evidence({ kind: "playlist", id: "OLAK5uy_test0001" });
    assertEquals(seen.length, n, "answered from the snapshot cache");
  } finally {
    db.close();
  }
});

Deno.test("a single video; a private playlist; a refused key and a used-up quota say so", async () => {
  const one = await setup({ videos: { items: [video("jNQXAC9IVRw", "Morning", "PT3M")] } });
  const e = await one.client.evidence({ kind: "video", id: "jNQXAC9IVRw" });
  assertEquals([e.kind, e.title, e.tracks.length, e.label], ["video", "Morning", 1, "LKult"]);
  one.db.close();

  const none = await setup({ playlists: { items: [] } });
  await assertRejects(() => none.client.evidence({ kind: "playlist", id: "PLprivate000" }), YouTubeError, "private");
  none.db.close();

  const refuse = (reason: string, message: string) =>
    new Response(JSON.stringify({ error: { code: 400, message, errors: [{ reason }] } }), { status: 400 });
  const bad = await setup({ videos: refuse("badRequest", "API key not valid. Please pass a valid API key.") });
  await assertRejects(() => bad.client.evidence({ kind: "video", id: "jNQXAC9IVRw" }), YouTubeKeyError, "refused");
  bad.db.close();
  const quota = await setup({ videos: refuse("quotaExceeded", "The request cannot be completed") });
  const err = await assertRejects(() => quota.client.evidence({ kind: "video", id: "jNQXAC9IVRw" }), YouTubeKeyError);
  assert(err.message.includes("quota") && !err.message.includes(KEY));
  quota.db.close();
});
