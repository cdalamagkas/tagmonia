/**
 * Generates a synthetic library for manual testing and the Phase 1 scale check
 * (a few hundred albums). Copies the generated blank fixtures and tags them via
 * TagIO. Writes only under --out (default dev/music, gitignored); refuses an
 * existing non-empty directory it did not create, so it can never touch a real library.
 *
 *   scripts/dk deno run --allow-read --allow-write --allow-env --allow-run=python3 scripts/gen_library.ts --albums 300
 */
import { parseArgs } from "node:util";
import { join } from "node:path";
import { createTagIO } from "../server/tagio/mod.ts";

const { values } = parseArgs({
  options: {
    out: { type: "string", default: "dev/music" },
    albums: { type: "string", default: "300" },
    tracks: { type: "string", default: "10" },
  },
});
const out = values.out!;
const albums = Number(values.albums);
const tracksPer = Number(values.tracks);
const MARKER = ".tagmony-generated";
const FORMATS = ["flac", "mp3", "m4a", "ogg", "opus"] as const;
const FIXTURES = join(import.meta.dirname!, "../tests/fixtures/audio");

try {
  const entries = await Array.fromAsync(Deno.readDir(out));
  if (entries.length && !entries.some((e) => e.name === MARKER)) {
    console.error(`${out} is not empty and was not created by this script; refusing to write there.`);
    Deno.exit(1);
  }
  await Deno.remove(out, { recursive: true });
} catch (e) {
  if (!(e instanceof Deno.errors.NotFound)) throw e;
}
await Deno.mkdir(out, { recursive: true });
await Deno.writeTextFile(join(out, MARKER), "generated by scripts/gen_library.ts\n");

const tagio = await createTagIO();
const started = performance.now();
let files = 0;
try {
  for (let a = 1; a <= albums; a++) {
    const fmt = FORMATS[a % FORMATS.length];
    const artist = a % 20 === 0 ? "Various Artists" : `Artist ${String(Math.ceil(a / 3)).padStart(3, "0")}`;
    const album = `Album ${String(a).padStart(4, "0")}`;
    const discs = a % 10 === 0 ? 2 : 1; // every tenth album is a two-disc set in CD1/CD2 folders
    const dir = join(out, artist, `${album} (${2000 + (a % 25)})`);
    for (let d = 1; d <= discs; d++) {
      const discDir = discs > 1 ? join(dir, `CD${d}`) : dir;
      await Deno.mkdir(discDir, { recursive: true });
      for (let t = 1; t <= tracksPer; t++) {
        const path = join(discDir, `${String(t).padStart(2, "0")} - Track ${t}.${fmt}`);
        await Deno.copyFile(join(FIXTURES, `blank.${fmt}`), path);
        await tagio.write(path, {
          set: {
            title: `Track ${t}`,
            artist: artist === "Various Artists" ? `Guest ${t}` : artist,
            albumartist: artist,
            album,
            tracknumber: t,
            totaltracks: tracksPer,
            discnumber: d,
            totaldiscs: discs,
            date: String(2000 + (a % 25)),
            genre: ["Electronic"],
          },
          remove: [],
        });
        files++;
      }
    }
  }
  // A folder of untagged files, as found in real libraries.
  await Deno.mkdir(join(out, "Unsorted"), { recursive: true });
  for (let i = 1; i <= 5; i++) await Deno.copyFile(join(FIXTURES, "blank.mp3"), join(out, "Unsorted", `track${i}.mp3`));
  files += 5;
} finally {
  await tagio.close?.();
}
console.log(`${files} files in ${albums} albums under ${out} (${((performance.now() - started) / 1000).toFixed(1)} s)`);
